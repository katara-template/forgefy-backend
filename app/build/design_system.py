def _patch_flutter_pubspec(root: Path) -> None:
    pubspec = root / "pubspec.yaml"
    if not pubspec.exists():
        return
    content = pubspec.read_text(encoding="utf-8")

    new_deps = {
        "google_fonts": "^6.2.1",
        "shimmer": "^3.0.0",
        "flutter_animate": "^4.5.0",
        "cached_network_image": "^3.3.1",
    }

    deps_pos = content.find("dependencies:")
    if deps_pos == -1:
        return

    lines = content.splitlines(keepends=True)
    insert_after = -1
    in_deps = False
    for i, line in enumerate(lines):
        stripped = line.strip()
        if stripped.startswith("dependencies:"):
            in_deps = True
            insert_after = i
            continue
        if in_deps:
            if stripped and not stripped.startswith("#") and not line.startswith(" ") and not line.startswith("\t"):
                break
            if stripped and stripped != "dependencies:" and not stripped.startswith("flutter:") and not stripped.startswith("sdk:"):
                insert_after = i

    additions = []
    for pkg, ver in new_deps.items():
        if f"{pkg}:" not in content:
            additions.append(f"  {pkg}: {ver}\n")

    if additions and insert_after >= 0:
        lines.insert(insert_after + 1, "".join(additions))
        pubspec.write_text("".join(lines), encoding="utf-8")


