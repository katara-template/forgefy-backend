def _hex(color: str) -> str:
    """Strip '#' and uppercase. Returns '000000' on bad input."""
    c = (color or "#000000").lstrip("#").upper()
    return c if len(c) == 6 else "000000"


def _font_camel(font_name: str) -> str:
    """'DM Sans' → 'dmSans' for GoogleFonts method calls."""
    words = re.split(r"[\s_-]+", (font_name or "inter").strip())
    return words[0].lower() + "".join(w.capitalize() for w in words[1:])


def _write_safe(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


