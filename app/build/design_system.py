def _write_nextjs_design_system(
    workspace_path: str,
    ds: dict,
    blueprint: dict,
    log_fn: LogFn = None,
) -> list[str]:
    root = Path(workspace_path)
    sig = ds.get("signature_element", "Primary-colored accent card")

    written: list[str] = []

    def w(rel: str, content: str) -> None:
        _write_safe(root / rel, content)
        written.append(rel)

    if log_fn:
        log_fn("tool", "Writing design tokens → Next.js theme files")

    # Only write globals.css if it doesn't exist yet (template may have one)
    globals_path = root / "app" / "globals.css"
    if not globals_path.exists():
        w("app/globals.css", _next_globals_css(ds))
    else:
        # Prepend our CSS variables to the existing file
        existing = globals_path.read_text(encoding="utf-8")
        if "--color-primary" not in existing:
            globals_path.write_text(_next_globals_css(ds) + "\n" + existing, encoding="utf-8")
            written.append("app/globals.css")

    w("lib/design-system/tokens.ts", _next_tokens_ts())
    w("tailwind.config.ts", _next_tailwind_config(ds))

    if log_fn:
        log_fn("tool", "Writing core UI components (7 files)")

    w("components/ui/Button.tsx", _next_button())
    w("components/ui/Card.tsx", _next_card())
    w("components/ui/TextField.tsx", _next_text_field())
    w("components/ui/Skeleton.tsx", _next_skeleton())
    w("components/ui/EmptyState.tsx", _next_empty_state())
    w("components/ui/SignatureWidget.tsx", _next_signature_widget(sig))

    _patch_next_package_json(root)

    if log_fn:
        log_fn("info", f"⌛ Signature element: {sig}")

    return written


def _patch_next_package_json(root: Path) -> None:
    pkg_path = root / "package.json"
    if not pkg_path.exists():
        return
    try:
        pkg = json.loads(pkg_path.read_text(encoding="utf-8"))
        deps = pkg.setdefault("dependencies", {})
        new_deps = {
            "framer-motion": "^11.0.0",
            "clsx": "^2.1.0",
            "tailwind-merge": "^2.3.0",
        }
        changed = False
        for k, v in new_deps.items():
            if k not in deps:
                deps[k] = v
                changed = True
        if changed:
            pkg_path.write_text(json.dumps(pkg, indent=2) + "\n", encoding="utf-8")
    except Exception as exc:
        logger.warning("Next.js package.json patch failed: %s", exc)


