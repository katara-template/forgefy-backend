def generate_design_system_files(
    workspace_path: str | Path,
    blueprint: dict[str, Any],
    framework: str,
    log_fn: LogFn = None,
) -> None:
    """Phase 0.5 — write design token + core component files to the workspace.

    Called AFTER the GitHub template repo is pushed, BEFORE the build agent runs.
    The build agent will read these files and use them as the source of truth for
    all visual decisions.
    """
    workspace_path = str(workspace_path)
    app_name = blueprint.get("app_name", "app")

    ds = blueprint.get("design_system") or {}
    if not ds:
        logger.info("No design_system in blueprint — using fallback for %s", app_name)
        ds = _generate_fallback_design_system(blueprint)

    if log_fn:
        log_fn("info", f"⌛ Generating design system for {app_name}…")
        log_fn("plan", json.dumps({"design_system": ds}))

    if framework == "flutter":
        written = _write_flutter_design_system(workspace_path, ds, blueprint, log_fn)
    elif framework == "react_native":
        written = _write_react_native_design_system(workspace_path, ds, blueprint, log_fn)
    elif framework in ("next", "nextjs"):
        written = _write_nextjs_design_system(workspace_path, ds, blueprint, log_fn)
    else:
        logger.warning("Unknown framework %r — skipping design system generation", framework)
        return

    if log_fn:
        log_fn("info", f"Design system ready ({len(written)} files) — starting build agent")
    logger.info("Design system materialised: %d files for %s (%s)", len(written), app_name, framework)
